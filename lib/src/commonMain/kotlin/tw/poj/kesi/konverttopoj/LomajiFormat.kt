enum class LomajiFormat {
    /** Pe̍h-ōe-jī with tone numbers, e.g. "tai5-gi2" */
    POJ_INPUT,
    /** Pe̍h-ōe-jī with Unicode diacriticals, e.g. "Tâi-gí" */
    POJ_UNICODE,
    /** Kàu-io̍k Pō͘ Lô-má-jī with tone numbers, e.g. "tai5-gi2" */
    KPL_INPUT,
    /** Kàu-io̍k Pō͘ Lô-má-jī with Unicode diacriticals, e.g. "Tâi-gí" */
    KPL_UNICODE
}
